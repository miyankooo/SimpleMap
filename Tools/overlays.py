"""Writes Data.lua: every world map overlay of the zones WoW Forever shows, from wago.tools DB2 exports.

Run from the repo root with the build to read: python3 Tools/overlays.py 1.60.1.70862
"""
import csv
import io
import sys
import urllib.request
from collections import defaultdict

build = sys.argv[1]


def table(name):
    url = f"https://wago.tools/db2/{name}/csv?build={build}"
    # wago.tools refuses urllib's default user agent.
    request = urllib.request.Request(url, headers={"User-Agent": "SimpleMap-overlays"})
    with urllib.request.urlopen(request) as response:
        return list(csv.DictReader(io.TextIOWrapper(response, "utf-8")))


zones = {row["ID"]: row["Name_lang"] for row in table("UiMap")}
arts = {row["UiMapArtID"]: zones.get(row["UiMapID"], "") for row in table("UiMapXMapArt")}

tiles = defaultdict(list)
for row in table("WorldMapOverlayTile"):
    if row["LayerIndex"] == "0":
        tiles[row["WorldMapOverlayID"]].append((int(row["RowIndex"]), int(row["ColIndex"]), row["FileDataID"]))

# Art no zone uses is left out, and so is an overlay without tiles.
overlays = defaultdict(list)
for row in table("WorldMapOverlay"):
    files = [file for _, _, file in sorted(tiles[row["ID"]])]
    if row["UiMapArtID"] in arts and files:
        fields = [row["TextureWidth"], row["TextureHeight"], row["OffsetX"], row["OffsetY"], *files]
        overlays[int(row["UiMapArtID"])].append("{ " + ", ".join(fields) + " }")

lines = [
    f"-- Generated by Tools/overlays.py from wago.tools, build {build}. Do not edit.",
    "local _, ns = ...",
    "",
    "-- [UiMapArtID] = { { width, height, offsetX, offsetY, fileDataID, ... } }, the tiles row by row.",
    "ns.overlays = {",
]
for art in sorted(overlays):
    lines.append(f"    [{art}] = {{ -- {arts[str(art)]}")
    lines.extend(f"        {overlay}," for overlay in overlays[art])
    lines.append("    },")
lines.append("}")

with open("Data.lua", "w", encoding="utf-8") as file:
    file.write("\n".join(lines) + "\n")
print(f"Data.lua: {sum(map(len, overlays.values()))} overlays in {len(overlays)} zones")
